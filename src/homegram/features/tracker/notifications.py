"""Home Assistant automation that pushes tracker changes to mobile devices.

The bot owns the automation (default id ``tracker_notifica``) and regenerates it from three
settings, all stored in the automation itself so Home Assistant stays the source of truth:

- the target devices: one ``notify.mobile_app_*`` action each;
- the muted products: the ``muted`` trigger variable;
- on/off: whether the automation entity is enabled.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

NOTIFY_PREFIX = "notify."
MOBILE_APP_PREFIX = "mobile_app_"
# Smallest price change (in the sensor's currency, €) worth a notification.
PRICE_THRESHOLD = 5

# Lower-case fragments of availability texts meaning "out of stock" (keep in sync with shops).
_OUT_OF_STOCK = (
    "['non disponibile','esaurito','currently unavailable','out of stock',"
    "'nicht verfügbar','derzeit nicht','indisponible','no disponible']"
)


def _in_stock(which: str) -> str:
    return (
        f"{{% set s = trigger.{which}_state.state if trigger.{which}_state else 'unknown' %}}"
        f"{{% set oos = {_OUT_OF_STOCK} %}}"
        "{{ (s | float(0) > 0) if is_number(s) else (s not in ['unknown','unavailable'] "
        "and (oos | select('in', s | lower) | list | length == 0)) }}"
    )


TRIGGER_VARIABLES: dict[str, str] = {
    "parts": (
        "{{ (trigger.to_state.attributes.friendly_name if trigger.to_state else '').split(' · ') }}"
    ),
    "prodotto": "{{ parts[0] }}",
    "shop": "{{ parts[1] if parts | length > 1 else '' }}",
    "kind": "{{ 'prezzo' if parts[2] == 'prezzo' else 'disponibilita' }}",
    "unit": (
        "{{ trigger.to_state.attributes.unit_of_measurement | default('') "
        "if trigger.to_state else '' }}"
    ),
    "url": (
        "{{ config_entry_attr(config_entry_id(trigger.entity_id), 'title') "
        "or '/dashboard-tracker' }}"
    ),
    "delta": (
        "{{ (trigger.to_state.state | float(0) - trigger.from_state.state | float(0)) | round(2) "
        "if trigger.from_state and trigger.to_state else 0 }}"
    ),
    "in_from": _in_stock("from"),
    "in_to": _in_stock("to"),
}

CONDITIONS: list[dict[str, Any]] = [
    {
        "condition": "template",
        "value_template": (
            "{% set bad = ['unknown','unavailable','none',''] %}"
            "{{ trigger.from_state is not none and trigger.to_state is not none "
            "and parts | length == 3 and prodotto not in muted "
            "and trigger.from_state.state not in bad and trigger.to_state.state not in bad "
            "and trigger.from_state.state != trigger.to_state.state }}"
        ),
    },
    # Prices: only changes of at least PRICE_THRESHOLD. Stock: only in stock <-> out of stock,
    # not every piece sold.
    {
        "condition": "template",
        "value_template": (
            "{{ (is_number(trigger.from_state.state) and is_number(trigger.to_state.state) "
            f"and delta | float(0) | abs >= {PRICE_THRESHOLD}) "
            "if kind == 'prezzo' else in_from != in_to }}"
        ),
    },
]

NOTIFY_DATA: dict[str, Any] = {
    # Prices: red dot when the price went up, green when it went down.
    "title": (
        "{{ (('🔴 ' if delta | float(0) > 0 else '🟢 ') if kind == 'prezzo' "
        "else ('✅ ' if in_to else '❌ ')) ~ prodotto }}"
    ),
    "message": (
        "{% if kind == 'prezzo' -%}\n"
        "{%- set f = trigger.from_state.state | float(0) -%}"
        "{%- set t = trigger.to_state.state | float(0) -%}\n"
        "{{ shop }}: {{ ('%.2f' | format(f)) | replace('.', ',') }} € → "
        "{{ ('%.2f' | format(t)) | replace('.', ',') }} € "
        "({{ '▼' if t < f else '▲' }} "
        "{{ ('%.2f' | format((t - f) | abs)) | replace('.', ',') }} €)\n"
        "{%- elif in_to -%}\n"
        "Di nuovo disponibile su {{ shop }} "
        "({{ trigger.to_state.state | trim }}{{ ' ' ~ unit if unit }})\n"
        "{%- else -%}\n"
        "Esaurito su {{ shop }}\n"
        "{%- endif %}"
    ),
    "data": {
        "clickAction": "{{ url }}",
        "url": "{{ url }}",
        "group": "tracker",
        "channel": "Tracker",
    },
}


@dataclass
class NotificationSettings:
    targets: list[str] = field(default_factory=list)  # notify services, e.g. mobile_app_s24
    muted: list[str] = field(default_factory=list)  # product names
    exists: bool = False


def parse(config: dict[str, Any] | None) -> NotificationSettings:
    """Read the settings back from an automation config generated by `build`."""
    if not config:
        return NotificationSettings()
    targets = []
    for action in config.get("actions", config.get("action")) or []:
        name = action.get("action") or action.get("service") or ""
        if name.startswith(NOTIFY_PREFIX):
            targets.append(name.removeprefix(NOTIFY_PREFIX))
    triggers = config.get("triggers", config.get("trigger")) or [{}]
    muted = (triggers[0].get("variables") or {}).get("muted") or []
    return NotificationSettings(
        targets=targets, muted=[str(m) for m in muted if isinstance(m, str)], exists=True
    )


def build(entities: list[str], settings: NotificationSettings) -> dict[str, Any]:
    """Full automation config for the given tracker sensors and settings."""
    return {
        "alias": "Tracker – notifica prezzo/disponibilità",
        "description": (
            "Generata dal bot HomeGram (/tracker_notifiche): non modificarla a mano, "
            "viene riscritta. Notifica i cambi di prezzo e disponibilità (disponibile ↔ "
            "esaurito) dei prodotti tracciati, letti dal nome dei sensori scrape "
            '"<prodotto> · <negozio> · prezzo|disponibilità".'
        ),
        "mode": "queued",
        "max": 30,
        "triggers": [
            {
                "trigger": "state",
                "entity_id": sorted(entities),
                "variables": {"muted": sorted(settings.muted), **TRIGGER_VARIABLES},
            }
        ],
        "conditions": CONDITIONS,
        "actions": [
            {"action": f"{NOTIFY_PREFIX}{target}", "data": NOTIFY_DATA}
            for target in sorted(settings.targets)
        ],
    }


def device_label(service: str) -> str:
    """`mobile_app_s24_ultra_di_davide` -> `S24 Ultra Di Davide`."""
    return service.removeprefix(MOBILE_APP_PREFIX).replace("_", " ").strip().title() or service
